from sklearn.cluster import KMeans
from sklearn.metrics import silhouette_score
from sklearn.preprocessing import StandardScaler
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline

num_cols = ['SeniorCitizen', 'tenure', 'MonthlyCharges', 'TotalCharges']
cat_cols = [col for col in df_encoded.columns if col not in num_cols + ['Churn']]

preprocessing = ColumnTransformer([
    ('num', StandardScaler(), num_cols),
    ('cat', 'passthrough', cat_cols)
])

kmeans_pipeline = Pipeline([
    ('preprocessing', preprocessing),
    ('kmeans', KMeans(n_clusters=3, random_state=42, n_init="auto"))
])

X_all = df_encoded.drop('Churn', axis=1)
kmeans_pipeline.fit(X_all)

clusters = kmeans_pipeline.named_steps['kmeans'].labels_
df_encoded['Cluster'] = clusters

sil_score = silhouette_score(preprocessing.fit_transform(X_all), clusters)
